"""The eval registry: named, versioned entries, one per property (Layer 6).

    evals/registry/<name>.yaml   id, version, property, description, task_dir, graders,
                                 metrics, split, owner_agent, canary
    evals/registry/CANARY.txt    the one contamination canary, embedded in every
                                 registry entry, every case.yaml and tasks.jsonl
    evals/registry/tasks.jsonl   every case flattened to one JSON record, generated by
                                 `python -m evals build-tasks` and committed

    load_registry()              -> {eval_id: entry}
    entry_for_property("P4")     -> the egress entry
    select(registry, ["egress", "security.boundary.v1", "P9"]) -> matching ids
    build_tasks(cases, registry) -> the tasks.jsonl records (list of dicts)
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Dict, Iterable, List, Optional

import yaml

from .graders import Case

REPO = Path(__file__).resolve().parents[1]
REGISTRY_DIR = REPO / "evals" / "registry"
CANARY_FILE = REGISTRY_DIR / "CANARY.txt"
TASKS_FILE = REGISTRY_DIR / "tasks.jsonl"

REQUIRED = ("id", "version", "property", "description", "task_dir", "graders",
            "metrics", "split", "owner_agent", "canary")


def canary(registry_dir: Path = REGISTRY_DIR) -> str:
    return (registry_dir / "CANARY.txt").read_text().strip()


def load_registry(registry_dir: Path = REGISTRY_DIR) -> Dict[str, Dict]:
    """Every `<name>.yaml` in the registry, keyed by eval id, validated."""
    want = canary(registry_dir)
    out: Dict[str, Dict] = {}
    for y in sorted(registry_dir.glob("*.yaml")):
        entry = yaml.safe_load(y.read_text()) or {}
        missing = [k for k in REQUIRED if k not in entry]
        if missing:
            raise ValueError(f"{y}: missing {missing}")
        entry.setdefault("name", y.stem)
        if entry["id"] != f"security.{entry['name']}.v{entry['version']}":
            raise ValueError(f"{y}: id {entry['id']!r} does not match name/version")
        if entry["canary"] != want:
            raise ValueError(f"{y}: canary differs from CANARY.txt")
        if not (registry_dir.parent / entry["task_dir"]).is_dir():
            raise ValueError(f"{y}: task_dir {entry['task_dir']!r} does not exist")
        entry["_file"] = str(y.relative_to(REPO)) if y.is_relative_to(REPO) else str(y)
        out[entry["id"]] = entry
    props = [e["property"] for e in out.values()]
    if len(set(props)) != len(props):
        raise ValueError("two registry entries claim the same property")
    return out


def entry_for_property(prop: str, registry: Optional[Dict[str, Dict]] = None) -> Optional[Dict]:
    registry = registry if registry is not None else load_registry()
    return next((e for e in registry.values() if e["property"] == prop), None)


def select(registry: Dict[str, Dict], selectors: Iterable[str]) -> List[str]:
    """Eval ids matching any selector: full id, id without version, short name, or
    property (P4). Unknown selectors raise so a typo cannot silently run nothing."""
    ids: List[str] = []
    for s in selectors:
        hits = [i for i, e in registry.items()
                if s in (i, i.rsplit(".v", 1)[0], e["name"], e["property"])]
        if not hits:
            raise ValueError(f"no eval matches {s!r}; try `python -m evals list`")
        ids += [h for h in hits if h not in ids]
    return ids


def task_record(case: Case, entry: Dict, repo: Path = REPO) -> Dict:
    rel = case.path.relative_to(repo) if case.path.is_relative_to(repo) else case.path
    return {
        "eval_id": entry["id"],
        "task_id": case.id,
        "property": case.property,
        "origin": case.origin,
        "grader": case.grader,
        "expect": case.expect,
        "description": " ".join(case.description.split()),
        "paths": {"case": str(rel), "vuln": str(rel / "vuln"), "clean": str(rel / "clean")},
        "canary": case.canary,
    }


def build_tasks(cases: Iterable[Case], registry: Optional[Dict[str, Dict]] = None) -> List[Dict]:
    """One record per case, in case-id order. Raises on a case whose property has no
    registry entry or whose canary is missing/wrong — the dataset must be whole."""
    registry = registry if registry is not None else load_registry()
    want = canary()
    by_prop = {e["property"]: e for e in registry.values()}
    records = []
    for c in sorted(cases, key=lambda c: c.id):
        entry = by_prop.get(c.property)
        if entry is None:
            raise ValueError(f"{c.id}: property {c.property} has no registry entry")
        if c.canary != want:
            raise ValueError(f"{c.id}: case.yaml canary missing or differs from CANARY.txt")
        records.append(task_record(c, entry))
    return records


def render_tasks(records: List[Dict]) -> str:
    return "".join(json.dumps(r, sort_keys=True, ensure_ascii=False) + "\n" for r in records)


def tasks_are_fresh(records: List[Dict], tasks_file: Path = TASKS_FILE) -> bool:
    return tasks_file.exists() and tasks_file.read_text() == render_tasks(records)
