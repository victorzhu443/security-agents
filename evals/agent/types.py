@dataclass
class TrialResult:
    """One line of samples.jsonl."""
    eval_id: str
    task_id: str
    trial: int
    property: str
    agent: str
    source: str
    scores: Scores
    stop_reason: str
    failure_reason: str
    cost_usd: float
    usage: Usage
    tool_calls: int
    denials: List[DenialEvent]
    elapsed_s: float
    provenance: Provenance
    variant: str = "agent"                # agent | noop | reference (baselines use the same record)
    # ---- calib seam keys (W-D fills them from the Task + Condition; defaults for mutation runs)
    condition: str = ""                   # prompts.Condition.name: class-blind | class-aware | ...+no_verifier
    kind: str = KIND_MUTATION
    split: str = ""
    is_negative: bool = False
    sub_scenario: str = ""
    library: str = ""
    contamination_bin: str = ""           # pre | post | unknown for `provenance.model`

    def to_record(self) -> Dict[str, Any]:
        return {
            "eval_id": self.eval_id, "task_id": self.task_id, "trial": self.trial,
            "variant": self.variant, "property": self.property, "agent": self.agent,
            "source": self.source, "passed": self.scores.passed, "scores": self.scores.to_dict(),
            "condition": self.condition, "kind": self.kind, "split": self.split,
            "is_negative": self.is_negative, "sub_scenario": self.sub_scenario,
            "library": self.library, "contamination_bin": self.contamination_bin,
            "stop_reason": self.stop_reason, "failure_reason": self.failure_reason,
            "cost_usd": round(self.cost_usd, 6),
            "tokens": dataclasses.asdict(self.usage) | {"total": self.usage.total},
            "tool_calls": self.tool_calls,
            "denials": [dataclasses.asdict(d) for d in self.denials],
            "elapsed_s": round(self.elapsed_s, 3),
            "provenance": self.provenance.to_dict(),
        }


@dataclass
class ValidityResult:
    """Outcome of the no-model validity gate for one task (Layer 7 rule 2)."""
    task_id: str
    eval_id: str
    valid: bool
    noop_fix: Optional[float]             # must be 0.0
    reference_fix: Optional[float]        # must be 1.0
    reason: str = ""                      # why quarantined; empty when valid
    seconds: float = 0.0
    mode: str = ""
    #: Calib gate details (W-B/W-D): {"noop_rc": 1, "reference_rc": 0, "suite_rc": 0, ...}.
    #: The advisory rules are rc-based (noop rc == 1 = tests failed, not a collection error).
    details: Dict[str, Any] = field(default_factory=dict)

    def to_record(self) -> Dict[str, Any]:
        return dataclasses.asdict(self)
