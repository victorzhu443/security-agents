"""Shared contracts of the agent-eval harness (EVALS-PLAN.md Phase 7, Layer 6).

Everything in `evals/agent/` codes against the records and interfaces defined here and
nowhere else. Owned by the integrator; workers do not edit this file (CONTRACTS.md).

    Task          one mutation of one repo's security/mutations.yaml, as a task record
    Scores        the four deterministic grades of one trial
    TrialResult   one task x trial: scores, cost, tokens, tool calls, denials, provenance
    Provenance    what was run, where, on what: image digest, repo commit, toolkit, model, mode
    Env           the tau-bench-style environment: reset(task) / exec(argv) / diff() / close()
    Grader        name + grade(ctx) -> GradeResult; four of them in graders.py
    LoopResult    what the model loop hands back before grading (no scores in it)
    DenialEvent   one denied or malformed model action (a scope-safety event)

Conventions: every score is a float in [0, 1]; a trial `passed` when all four are 1.0.
Timestamps are UTC ISO-8601. Paths inside a task (`file`) are relative to the repo root.
"""
