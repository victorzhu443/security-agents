# --------------------------------------------------------------------- task

@dataclass(frozen=True)
class Task:
    """One mutation of one repo, as a task record (Layer 7 rule 1: `source`)."""
    task_id: str                  # the mutation id, e.g. P4-arxiv-allowlist-dropped
    eval_id: str                  # security.agent.<repo>.v1
    repo: str                     # key in evals/agent/repos.yaml
    repo_url: str                 # https clone URL (CI has no local checkout)
    commit: str                   # full sha the task is pinned to
    property: str                 # P1..P9
    description: str
    file: str                     # the mutated file, relative to the repo root
    find: str                     # the fixed code (reference)
    replace: str                  # the pre-fix code (what the agent sees)
    hidden_test: str              # the mutation's test command, as written in the catalogue
    suite_test: str               # the repo's default `test` command (the whole security suite)
    container_test: List[str]     # hidden_test mapped to the container (tasks.py documents the map)
    pythonpath: List[str]         # catalogue `pythonpath`, relative to the repo root
    agent: str                    # agents/<name>.md for `property`
    canary: str
    source: str = SOURCE_REAL_CODEBASE
    repo_path: Optional[str] = None   # local checkout when one exists (cloned from, never run in)

    def to_record(self) -> Dict[str, Any]:
        return dataclasses.asdict(self)


# --------------------------------------------------------------------- environment

@dataclass
class ExecResult:
    returncode: int               # 124 on timeout, 137 when killed by a limit
    stdout: str
    stderr: str
    seconds: float
    timed_out: bool = False


@dataclass
class ResetInfo:
    """What `Env.reset` set up; copied into Provenance by the runner."""
    mode: str                     # "container" | "local"
    workdir: Path                 # host path of the clone (the only writable mount)
    image: Optional[str] = None   # image tag in container mode
    image_digest: Optional[str] = None
    container: Optional[str] = None
    limits: Dict[str, Any] = field(default_factory=dict)


class Env(Protocol):
    """tau-bench-shaped environment (EVALS-PLAN.md Layer 6, Phase 7).

    Contract:
      * `reset(task)` clones `task.repo_url` (or `task.repo_path` when present) at
        `task.commit` into a fresh temp dir, applies the mutation with
        `evals.mutate.apply_mutation`, and makes the clone the only writable location the
        model's commands can reach. Container mode: per-repo image (python:3.12-slim + the
        repo's requirements, cached by requirements hash), `--read-only`, `--network none`,
        `--pids-limit`, `--memory`, `--user <host uid:gid>`, `--cap-drop ALL`,
        `--security-opt no-new-privileges`, `--ulimit fsize/cpu`, `--tmpfs /tmp`, the clone
        at /work. Local mode (docker unavailable): the same clone, commands run with the
        sandbox's local-mode rlimits and a process-group kill on timeout; `mode == "local"`.
      * `exec(argv)` runs one command inside (cwd = the clone root), never a shell string.
      * `diff()` returns `git diff` of the clone against `task.commit` plus the mutation,
        i.e. only what the agent changed (the mutation itself is committed by reset so it is
        not in the diff). Untracked files appear as additions.
      * `close()` kills the container (if any) and removes the temp dir. Idempotent.
      * `workdir` is the host path of the clone. Graders and baselines may read and write
        it directly (they are the harness, outside the box); the model's tools never do,
        they go through `exec`.
    """
    mode: str
    workdir: Optional[Path]

    def reset(self, task: Task) -> ResetInfo: ...
    def exec(self, argv: Sequence[str], *, timeout_s: int = 600) -> ExecResult: ...
    def diff(self) -> str: ...
    def close(self) -> None: ...


# --------------------------------------------------------------------- model loop

@dataclass
class DenialEvent:
    """A denied or malformed model action — logged, returned to the model as an error
    tool_result, and counted by the scope-safety grader."""
    tool: str                     # tool name as the model gave it (may be unknown)
    reason: str                   # categorical: unknown_tool | bad_args | path_escape |
                                  # not_test_command | invalid_report | ...
    detail: str = ""              # short, no secrets
    call_index: int = 0


@dataclass
class Usage:
    input_tokens: int = 0
    output_tokens: int = 0
    cache_read_tokens: int = 0
    cache_write_tokens: int = 0

    @property
    def total(self) -> int:
        return self.input_tokens + self.output_tokens + self.cache_read_tokens + self.cache_write_tokens

    def add(self, other: "Usage") -> None:
        self.input_tokens += other.input_tokens
        self.output_tokens += other.output_tokens
        self.cache_read_tokens += other.cache_read_tokens
        self.cache_write_tokens += other.cache_write_tokens


@dataclass
class LoopResult:
    """What loop.run_trial returns. No scores: the loop never grades itself."""
    stop_reason: str                      # STOP_DONE | STOP_BUDGET | STOP_REFUSAL | STOP_ERROR
    report: Optional[Dict[str, Any]]      # the validated security-report.json, or None
    tool_calls: int
    denials: List[DenialEvent]
    usage: Usage
    cost_usd: float
    model: str
    failure_reason: str = ""              # "budget: 40 tool calls", "api: ...", ...
    transcript: List[Dict[str, Any]] = field(default_factory=list)   # redacted, for the run dir
    elapsed_s: float = 0.0


# --------------------------------------------------------------------- grading

@dataclass
class GradeContext:
    task: Task
    env: Env                              # reset to the task, with the agent's edits applied
    report: Optional[Dict[str, Any]]
    diff: str
    denials: List[DenialEvent]


@dataclass
class GradeResult:
    value: float                          # in [0, 1]
    evidence: str = ""                    # oracle output, not a sentence
    error: Optional[str] = None           # grader could not run; value is 0.0


class Grader(Protocol):
    name: str
    def grade(self, ctx: GradeContext) -> GradeResult: ...


@dataclass
class Scores:
    recall: float = 0.0
    fix: float = 0.0
    claim_fidelity: float = 0.0
    scope_safety: float = 0.0
    evidence: Dict[str, str] = field(default_factory=dict)
    errors: Dict[str, str] = field(default_factory=dict)

    @property
    def passed(self) -> bool:
        return all(v >= 1.0 for v in (self.recall, self.fix, self.claim_fidelity, self.scope_safety))

    def to_dict(self) -> Dict[str, Any]:
        return {"recall": self.recall, "fix": self.fix, "claim_fidelity": self.claim_fidelity,
                "scope_safety": self.scope_safety, "passed": self.passed,
                "evidence": self.evidence, "errors": self.errors}


# --------------------------------------------------------------------- results

@dataclass
class Provenance:
    mode: str                             # container | local
    repo: str
    repo_commit: str
    toolkit_version: str
    toolkit_sha: str
    model: str
    image: Optional[str] = None
    image_digest: Optional[str] = None
    seed: Optional[int] = None
    python: str = ""
    platform: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return dataclasses.asdict(self)


@dataclass
class TrialResult:
    """One line of samples.jsonl."""
    eval_id: str
    task_id: str
    trial: int
    property: str
    agent: str
    source: str
    scores: Scores
    stop_reason: str
    failure_reason: str
    cost_usd: float
    usage: Usage
    tool_calls: int
    denials: List[DenialEvent]
    elapsed_s: float
    provenance: Provenance
    variant: str = "agent"                # agent | noop | reference (baselines use the same record)

    def to_record(self) -> Dict[str, Any]:
        return {
            "eval_id": self.eval_id, "task_id": self.task_id, "trial": self.trial,
            "variant": self.variant, "property": self.property, "agent": self.agent,
            "source": self.source, "passed": self.scores.passed, "scores": self.scores.to_dict(),
            "stop_reason": self.stop_reason, "failure_reason": self.failure_reason,
            "cost_usd": round(self.cost_usd, 6),
            "tokens": dataclasses.asdict(self.usage) | {"total": self.usage.total},
            "tool_calls": self.tool_calls,
            "denials": [dataclasses.asdict(d) for d in self.denials],
            "elapsed_s": round(self.elapsed_s, 3),
            "provenance": self.provenance.to_dict(),
        }


@dataclass
class ValidityResult:
    """Outcome of the no-model validity gate for one task (Layer 7 rule 2)."""
    task_id: str
    eval_id: str
    valid: bool
    noop_fix: Optional[float]             # must be 0.0
    reference_fix: Optional[float]        # must be 1.0
    reason: str = ""                      # why quarantined; empty when valid
    seconds: float = 0.0
    mode: str = ""

    def to_record(self) -> Dict[str, Any]:
        return dataclasses.asdict(self)
