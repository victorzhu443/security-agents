"""Regression gates and trends (EVALS-PLAN.md Layer 4, Phase 6).

    python -m evals baseline publish [--label vX.Y.Z]   # commit this run's summary as a baseline
    python -m evals baseline list                       # every published baseline
    python -m evals baseline trends                     # regenerate evals/TRENDS.md only
    python -m evals gate [--against latest|<label>]     # compare the last run; exit 0/1/2

Published baselines live in `evals/baselines/<label>.json`, a committed copy of a run's
`summary.json` (per eval: n, recall, precision, Wilson CIs, errors; per task: passed).
`evals/baselines/latest.json` names the current one. Built baselines are immutable: a
label is never overwritten, the next release publishes the next one.

The gate's decision rule, per eval present in the baseline:

  * errors > 0 in the new run                              -> FAIL
  * new recall    < baseline's recall    lower 95% bound   -> FAIL  (outside noise)
  * new precision < baseline's precision lower 95% bound   -> FAIL  (outside noise)
  * a drop that stays above the bound is reported as "within noise" and passes
  * any task that passed in the baseline and fails now     -> FAIL  (a named regression
    is always a failure, whatever the aggregate says — with 54 tasks one flip moves
    recall from 1.00 to 0.98, well inside the 95% interval)

An eval the baseline has but the run does not is "could not evaluate" (exit 2): a
narrowed run must not pass the gate by omission. An eval new to the run has no bound
and is gated on errors only. A task in the baseline that the run no longer grades is
printed as a warning; the trend table's `cases` column shows the corpus shrinking.

Exit codes: 0 pass, 1 regression, 2 could not evaluate (no baseline, no run, eval missing).

`evals/TRENDS.md` is one row per published baseline (label, date, cases, recall,
precision, historical misses) and is regenerated by `baseline publish`.

The agent gate (Phase 1, W-D) applies the SAME rule to a published AGENT baseline:

    python -m evals baseline publish --agent --label vX [--summary PATH]   # agent-run or calib-run summary
    python -m evals gate --agent [--against latest|<label>] [--summary PATH]

Agent baselines live in `evals/baselines/agent/<label>.json` (immutable, `latest.json` pointer),
built from an `agent-run` or `calib-run` summary: per eval `pass_rate` and the four scores
(recall, fix, claim_fidelity, scope_safety) with their Wilson CIs and `errors`; per task
`passed` (all trials). The decision: errors > 0 -> FAIL; pass_rate or any of the four scores
below the baseline's lower 95% bound -> FAIL; a task that passed in the baseline and fails now
-> FAIL (named); an eval the baseline has but the run lacks -> exit 2. A summary without a
`tasks` list (agent-run's shape) gets one from the run's `samples.jsonl` (agent-variant rows,
`passed` = every trial passed) when the run dir is known.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from .metrics import fmt_ci
from .run import RESULTS, git_sha

REPO = Path(__file__).resolve().parents[1]
BASELINES = REPO / "evals" / "baselines"
TRENDS = REPO / "evals" / "TRENDS.md"
SCHEMA = 1
LABEL_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._+-]*$")

EVAL_FIELDS = ("property", "name", "split", "n", "tasks", "recall_hits", "precision_hits",
               "recall", "recall_ci95", "precision", "precision_ci95", "passed", "errors",
               "historical_misses", "trials", "pass_at_k", "pass_pow_k")

#: The agent gate (module docstring): baselines dir, the gated metrics, the copied fields.
AGENT_BASELINES = BASELINES / "agent"
DETECTOR_METRICS: Tuple[str, ...] = ("recall", "precision")
AGENT_METRICS: Tuple[str, ...] = ("pass_rate", "recall", "fix", "claim_fidelity", "scope_safety")
AGENT_EVAL_FIELDS = ("repo", "n", "tasks", "positives", "negatives", "trials", "passed", "errors",
                     "pass_at_k", "pass_pow_k", "cost_usd_per_task", "fpr", "fpr_ci95", "fp") + \
    tuple(f for m in AGENT_METRICS for f in (m, f"{m}_ci95"))


class GateError(Exception):
    """The gate could not be evaluated (exit 2), as opposed to a regression (exit 1)."""


# ----------------------------------------------------------------- summaries

def load_latest_summary(results_dir: Path = RESULTS) -> Dict:
    """The summary.json of the run `results/latest.json` points to."""
    pointer = results_dir / "latest.json"
    if not pointer.is_file():
        raise GateError(f"no run to evaluate: {pointer} does not exist (run `python -m evals run` first)")
    run_id = json.loads(pointer.read_text()).get("run_id")
    path = results_dir / str(run_id) / "summary.json"
    if not path.is_file():
        raise GateError(f"run {run_id!r} named by {pointer} has no {path.name}")
    return json.loads(path.read_text())


def load_summary(path: Optional[Path], results_dir: Path = RESULTS) -> Dict:
    if path is None:
        return load_latest_summary(results_dir)
    if not path.is_file():
        raise GateError(f"summary {path} does not exist")
    return json.loads(path.read_text())


# ----------------------------------------------------------------- baselines

def validate_label(label: str) -> str:
    if label == "latest" or not LABEL_RE.match(label):
        raise GateError(f"invalid baseline label {label!r}: letters, digits, . _ + -; not 'latest'")
    return label


def baseline_from_summary(summary: Dict, label: str, *, published: Optional[str] = None) -> Dict:
    """The committed shape: the run's aggregates plus one `passed` per task."""
    evals = {}
    for eid, b in summary.get("evals", {}).items():
        evals[eid] = {k: b[k] for k in EVAL_FIELDS if k in b}
    tasks = {}
    for t in summary.get("tasks", []):
        tasks[t["task_id"]] = {"eval_id": t.get("eval_id"), "property": t.get("property"),
                               "origin": t.get("origin"), "passed": bool(t.get("passed")),
                               "error": t.get("error")}
    return {
        "schema": SCHEMA,
        "label": validate_label(label),
        "published": published or dt.datetime.now(dt.timezone.utc).date().isoformat(),
        "run_id": summary.get("run_id"),
        "git_sha": summary.get("git_sha"),
        "toolkit_version": summary.get("toolkit_version"),
        "generated": summary.get("generated"),
        "trials": summary.get("trials", 1),
        "evals_selected": summary.get("evals_selected", list(evals)),
        "overall": summary.get("overall", {}),
        "evals": evals,
        "tasks": tasks,
        "_reading": {
            "evals": "per eval: n, recall, precision with Wilson 95% CIs, errors, historical "
                     "misses — the gate fails a run whose point estimate falls below *_ci95[0]",
            "tasks": "task_id -> passed; the gate fails any task that passed here and fails now",
        },
    }


def baseline_path(label: str, baselines_dir: Path = BASELINES) -> Path:
    return baselines_dir / f"{label}.json"


def publish(summary: Dict, label: Optional[str], baselines_dir: Path = BASELINES, *,
            published: Optional[str] = None, trends_path: Optional[Path] = None) -> Path:
    """Write `<label>.json`, point latest.json at it, regenerate the trend table.
    Refuses to overwrite an existing label (baselines are immutable)."""
    label = label or str(summary.get("git_sha") or "nogit")
    base = baseline_from_summary(summary, label, published=published)
    path = baseline_path(base["label"], baselines_dir)
    if path.exists():
        raise GateError(f"baseline {base['label']!r} already exists at {path}; pick a new --label")
    baselines_dir.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(base, indent=1, sort_keys=False) + "\n")
    (baselines_dir / "latest.json").write_text(json.dumps(
        {"label": base["label"], "file": path.name, "published": base["published"],
         "run_id": base["run_id"], "git_sha": base["git_sha"]}, indent=1) + "\n")
    write_trends(baselines_dir, trends_path)
    return path


def list_baselines(baselines_dir: Path = BASELINES) -> List[Dict]:
    """Every published baseline, oldest first (by published date, then label)."""
    out = []
    for p in baselines_dir.glob("*.json"):
        if p.name == "latest.json":
            continue
        try:
            b = json.loads(p.read_text())
        except json.JSONDecodeError as e:
            raise GateError(f"{p}: not valid JSON ({e})")
        if b.get("schema") != SCHEMA:
            raise GateError(f"{p}: schema {b.get('schema')!r}, this code reads {SCHEMA}")
        b["_file"] = p.name
        out.append(b)
    out.sort(key=lambda b: (b.get("published") or "", b.get("label") or ""))
    return out


def load_baseline(against: str = "latest", baselines_dir: Path = BASELINES) -> Dict:
    if against == "latest":
        pointer = baselines_dir / "latest.json"
        if not pointer.is_file():
            raise GateError(f"no published baseline: {pointer} does not exist "
                            "(publish one with `python -m evals baseline publish`)")
        against = json.loads(pointer.read_text()).get("label", "")
    path = baseline_path(against, baselines_dir)
    if not path.is_file():
        raise GateError(f"baseline {against!r} not found at {path}")
    b = json.loads(path.read_text())
    if b.get("schema") != SCHEMA:
        raise GateError(f"{path}: schema {b.get('schema')!r}, this code reads {SCHEMA}")
    return b


# ----------------------------------------------------------------- the decision

@dataclass
class EvalVerdict:
    eval_id: str
    base: Optional[Dict]              # None when the eval is new to this run
    new: Optional[Dict]               # None when the run did not grade it (exit 2)
    failures: List[str] = field(default_factory=list)
    notes: List[str] = field(default_factory=list)

    @property
    def verdict(self) -> str:
        if self.new is None:
            return "MISSING"
        if self.failures:
            return "FAIL"
        return "pass"


@dataclass
class Decision:
    baseline_label: str
    run_id: str
    rows: List[EvalVerdict]
    named: List[Tuple[str, str, str]]          # (task_id, eval_id, detail)
    missing_tasks: List[str]
    problems: List[str]                         # anything that makes the gate unevaluable

    @property
    def exit_code(self) -> int:
        if self.problems:
            return 2
        if self.named or any(r.failures for r in self.rows):
            return 1
        return 0

    @property
    def status(self) -> str:
        return {0: "PASS", 1: "FAIL", 2: "COULD NOT EVALUATE"}[self.exit_code]


def _metric_check(name: str, base: Dict, new: Dict) -> Tuple[Optional[str], Optional[str]]:
    """-> (failure, note). Fails when the new point estimate is below the baseline's
    lower Wilson bound; a smaller drop is a note."""
    b, n = base.get(name), new.get(name)
    ci = base.get(f"{name}_ci95")
    if b is None or n is None or not ci:
        return None, None
    lower = ci[0]
    if n < lower:
        return f"{name} {n:.3f} < baseline lower bound {lower:.3f} (baseline {b:.3f})", None
    if n < b:
        return None, f"{name} {b:.3f} -> {n:.3f}, within noise (bound {lower:.3f})"
    return None, None


def decide(baseline: Dict, summary: Dict) -> Decision:
    """Pure: apply the rule in the module docstring to a baseline and a run summary."""
    return _decide(baseline, summary, DETECTOR_METRICS)


def decide_agent(baseline: Dict, summary: Dict) -> Decision:
    """The same rule on an agent baseline: errors, pass_rate and the four scores below the
    baseline's lower Wilson bound, named task flips."""
    if baseline.get("kind") != "agent":
        raise GateError(f"baseline {baseline.get('label')!r} is not an agent baseline (kind={baseline.get('kind')!r}); "
                        "publish one with `baseline publish --agent`")
    return _decide(baseline, summary, AGENT_METRICS)


def _decide(baseline: Dict, summary: Dict, metrics: Tuple[str, ...]) -> Decision:
    rows: List[EvalVerdict] = []
    problems: List[str] = []
    new_evals: Dict[str, Dict] = summary.get("evals", {}) or {}
    base_evals: Dict[str, Dict] = baseline.get("evals", {}) or {}

    for eid, b in base_evals.items():
        n = new_evals.get(eid)
        v = EvalVerdict(eid, b, n)
        if n is None:
            problems.append(f"eval {eid} is in the baseline but this run did not grade it")
            rows.append(v)
            continue
        if n.get("errors"):
            v.failures.append(f"errors={n['errors']}")
        if not b.get("n"):
            v.notes.append("baseline has n=0; no bound")
        else:
            for metric in metrics:
                fail, note = _metric_check(metric, b, n)
                if fail:
                    v.failures.append(fail)
                if note:
                    v.notes.append(note)
        rows.append(v)
    for eid, n in new_evals.items():
        if eid in base_evals:
            continue
        v = EvalVerdict(eid, None, n, notes=["new eval; no baseline bound"])
        if n.get("errors"):
            v.failures.append(f"errors={n['errors']}")
        rows.append(v)

    overall_errors = (summary.get("overall") or {}).get("errors") or 0
    if overall_errors and not any("errors=" in f for r in rows for f in r.failures):
        # errors on a task outside every eval block; still a failure
        rows.append(EvalVerdict("_overall", None, summary.get("overall"),
                                failures=[f"errors={overall_errors}"]))

    new_tasks = {t["task_id"]: t for t in summary.get("tasks", []) or []}
    named: List[Tuple[str, str, str]] = []
    missing: List[str] = []
    for tid, bt in (baseline.get("tasks") or {}).items():
        if not bt.get("passed"):
            continue
        nt = new_tasks.get(tid)
        if nt is None:
            missing.append(tid)
            continue
        if not nt.get("passed"):
            detail = nt.get("error") or f"passed {nt.get('passes', 0)}/{nt.get('trials', 1)} trials"
            named.append((tid, str(nt.get("eval_id") or bt.get("eval_id")), str(detail)))

    return Decision(baseline_label=str(baseline.get("label")), run_id=str(summary.get("run_id")),
                    rows=rows, named=named, missing_tasks=missing, problems=problems)


# ----------------------------------------------------------------- rendering

def _cell(b: Optional[Dict], n: Optional[Dict], metric: str) -> str:
    def val(d):
        return "—" if d is None or d.get(metric) is None else f"{d[metric]:.2f}"
    bound = ""
    if b and b.get(f"{metric}_ci95"):
        bound = f" (bound {b[f'{metric}_ci95'][0]:.2f})"
    return f"{val(b)} -> {val(n)}{bound}"


def render_decision(d: Decision, baseline: Dict, metrics: Tuple[str, ...] = DETECTOR_METRICS) -> str:
    kind = "agent baseline" if baseline.get("kind") == "agent" else "baseline"
    lines = [f"gate: run {d.run_id} against {kind} {d.baseline_label} "
             f"(published {baseline.get('published')}, run {baseline.get('run_id')})", ""]
    table = [("eval", "n") + tuple(f"{m} (baseline -> new)" for m in metrics) + ("errors", "verdict")]
    for r in d.rows:
        n_val = "—" if r.new is None else str(r.new.get("n", "—"))
        if r.base is not None and r.new is not None and r.base.get("n") != r.new.get("n"):
            n_val = f"{r.base.get('n')} -> {r.new.get('n')}"
        errs = "—" if r.new is None else str(r.new.get("errors", 0))
        table.append((r.eval_id, n_val) + tuple(_cell(r.base, r.new, m) for m in metrics) + (errs, r.verdict))
    widths = [max(len(row[i]) for row in table) for i in range(len(table[0]))]
    for i, row in enumerate(table):
        lines.append("  ".join(c.ljust(w) for c, w in zip(row, widths)).rstrip())
        if i == 0:
            lines.append("  ".join("-" * w for w in widths))
    details = [(r.eval_id, f) for r in d.rows for f in r.failures] + \
              [(r.eval_id, n) for r in d.rows for n in r.notes]
    if details:
        lines.append("")
        for eid, text in details:
            lines.append(f"  {eid}: {text}")
    if d.named:
        lines += ["", f"Named regressions ({len(d.named)}; passed in the baseline, fail now):"]
        for tid, eid, detail in d.named:
            lines.append(f"  - {tid} ({eid}): {detail}")
    if d.missing_tasks:
        lines += ["", f"Warning: {len(d.missing_tasks)} baseline task(s) not graded in this run: "
                  + ", ".join(d.missing_tasks)]
    if d.problems:
        lines += ["", "Could not evaluate:"] + [f"  - {p}" for p in d.problems]
    n_evals_fail = sum(1 for r in d.rows if r.failures)
    lines += ["", f"GATE: {d.status} — {len(d.named)} named regression(s), "
              f"{n_evals_fail} eval(s) failing, {len(d.problems)} problem(s)"]
    return "\n".join(lines) + "\n"


def render_trends(baselines: List[Dict], latest_label: Optional[str] = None) -> str:
    lines = ["# Evals — trends", "",
             "One row per published baseline (`python -m evals baseline publish`), oldest first.",
             "`python -m evals gate` compares every run against the latest one: a run fails when",
             "recall or precision falls below that baseline's lower Wilson 95% bound, when any task",
             "that passed there fails now, or when a grader errors (EVALS-PLAN.md Layer 4).",
             "Generated by `baseline publish`; do not edit.", "",
             "| label | published | toolkit | run | cases | historical misses | recall | precision | errors |",
             "|---|---|---|---|---|---|---|---|---|"]
    for b in baselines:
        o = b.get("overall") or {}
        label = b.get("label", "?")
        if latest_label and label == latest_label:
            label = f"**{label}** (latest)"
        rec = fmt_ci(o["recall"], o["recall_ci95"]) if o.get("recall") is not None else "—"
        pre = fmt_ci(o["precision"], o["precision_ci95"]) if o.get("precision") is not None else "—"
        lines.append(f"| {label} | {b.get('published', '?')} | {b.get('toolkit_version', '?')} | "
                     f"`{b.get('run_id', '?')}` | {o.get('tasks', o.get('n', '?'))} | "
                     f"{o.get('historical_misses', '?')} | {rec} | {pre} | {o.get('errors', '?')} |")
    if not baselines:
        lines.append("| — | — | — | — | — | — | — | — | — |")
    return "\n".join(lines) + "\n"


def write_trends(baselines_dir: Path = BASELINES, trends_path: Optional[Path] = None) -> Path:
    trends_path = trends_path or (baselines_dir.parent / "TRENDS.md")
    latest = None
    pointer = baselines_dir / "latest.json"
    if pointer.is_file():
        latest = json.loads(pointer.read_text()).get("label")
    trends_path.write_text(render_trends(list_baselines(baselines_dir), latest))
    return trends_path


# ----------------------------------------------------------------- the agent gate

def agent_tasks_from_samples(rows: List[Dict]) -> List[Dict]:
    """Per-task `passed` (every agent-variant trial passed) from samples.jsonl rows that
    lack a summary `tasks` list (agent-run's shape)."""
    per: Dict[str, List[Dict]] = {}
    for r in rows:
        if r.get("variant", "agent") != "agent":
            continue
        per.setdefault(str(r["task_id"]), []).append(r)
    out = []
    for tid, rs in sorted(per.items()):
        errs = [(r.get("scores") or {}).get("errors", {}).get("trial") or r.get("failure_reason") for r in rs
                if r.get("stop_reason") not in (None, "done")]
        out.append({"task_id": tid, "eval_id": rs[0].get("eval_id"), "property": rs[0].get("property"),
                    "trials": len(rs), "passes": sum(bool(r.get("passed")) for r in rs),
                    "passed": all(bool(r.get("passed")) for r in rs), "error": errs[0] if errs else None})
    return out


def agent_summary_tasks(summary: Dict, run_dir: Optional[Path] = None) -> List[Dict]:
    if summary.get("tasks") is not None:
        return list(summary["tasks"])
    if run_dir is not None and (Path(run_dir) / "samples.jsonl").is_file():
        rows = [json.loads(l) for l in (Path(run_dir) / "samples.jsonl").read_text().splitlines() if l.strip()]
        return agent_tasks_from_samples(rows)
    return []


def agent_baseline_from_summary(summary: Dict, label: str, *, published: Optional[str] = None,
                                run_dir: Optional[Path] = None) -> Dict:
    """The committed agent-baseline shape (kind "agent"): per eval the gated metrics with
    their CIs and errors; per task `passed`."""
    evals = {}
    for eid, b in (summary.get("evals") or {}).items():
        evals[eid] = {k: b[k] for k in AGENT_EVAL_FIELDS if k in b}
    tasks = {}
    for t in agent_summary_tasks(summary, run_dir):
        tasks[t["task_id"]] = {"eval_id": t.get("eval_id"), "property": t.get("property"),
                               "passed": bool(t.get("passed")), "error": t.get("error")}
    return {
        "schema": SCHEMA, "kind": "agent",
        "label": validate_label(label),
        "published": published or dt.datetime.now(dt.timezone.utc).date().isoformat(),
        "run_id": summary.get("run_id"), "git_sha": summary.get("git_sha"),
        "toolkit_version": summary.get("toolkit_version"), "generated": summary.get("generated"),
        "model": summary.get("model"), "condition": summary.get("condition", ""), "split": summary.get("split", ""),
        "mode": summary.get("mode", ""), "trials": summary.get("trials", 1),
        "overall": {k: v for k, v in (summary.get("overall") or {}).items() if k in AGENT_EVAL_FIELDS},
        "evals": evals, "tasks": tasks,
        "_reading": {
            "evals": "per eval: pass_rate and recall/fix/claim_fidelity/scope_safety with Wilson 95% CIs, errors — "
                     "the agent gate fails a run whose point estimate falls below *_ci95[0]",
            "tasks": "task_id -> passed (every trial); the gate fails any task that passed here and fails now",
        },
    }


def publish_agent(summary: Dict, label: Optional[str], baselines_dir: Path = AGENT_BASELINES, *,
                  published: Optional[str] = None, run_dir: Optional[Path] = None) -> Path:
    """Write `agent/<label>.json` and point `agent/latest.json` at it; labels are immutable."""
    label = label or str(summary.get("git_sha") or "nogit")
    base = agent_baseline_from_summary(summary, label, published=published, run_dir=run_dir)
    path = baseline_path(base["label"], baselines_dir)
    if path.exists():
        raise GateError(f"agent baseline {base['label']!r} already exists at {path}; pick a new --label")
    baselines_dir.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(base, indent=1, sort_keys=False) + "\n")
    (baselines_dir / "latest.json").write_text(json.dumps(
        {"label": base["label"], "file": path.name, "published": base["published"],
         "run_id": base["run_id"], "git_sha": base["git_sha"]}, indent=1) + "\n")
    return path


def load_agent_summary(path: Optional[Path], results_dir: Path = RESULTS) -> Tuple[Dict, Optional[Path]]:
    """-> (summary, run_dir). Default: the run `latest-calib.json` names, else `latest-agent.json`."""
    if path is not None:
        if not path.is_file():
            raise GateError(f"summary {path} does not exist")
        return json.loads(path.read_text()), path.parent
    for pointer in (results_dir / "latest-calib.json", results_dir / "latest-agent.json"):
        if pointer.is_file():
            run_id = json.loads(pointer.read_text()).get("run_id")
            p = results_dir / str(run_id) / "summary.json"
            if not p.is_file():
                raise GateError(f"run {run_id!r} named by {pointer} has no {p.name}")
            return json.loads(p.read_text()), p.parent
    raise GateError(f"no agent run to evaluate: neither latest-calib.json nor latest-agent.json exists in {results_dir}")


# ----------------------------------------------------------------- CLIs

def gate_main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m evals gate", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--against", default="latest", metavar="LABEL",
                    help="baseline label, or 'latest' (default)")
    ap.add_argument("--summary", default=None, metavar="PATH",
                    help="summary.json to gate (default: the run evals/results/latest.json names)")
    ap.add_argument("--results", default=str(RESULTS), metavar="DIR")
    ap.add_argument("--baselines", default=None, metavar="DIR",
                    help=f"default {BASELINES} (detector) or {AGENT_BASELINES} (--agent)")
    ap.add_argument("--agent", action="store_true",
                    help="gate an agent-run / calib-run summary against a published agent baseline")
    ap.add_argument("--quiet", action="store_true", help="print only the verdict line")
    args = ap.parse_args(argv)
    bdir = Path(args.baselines) if args.baselines else (AGENT_BASELINES if args.agent else BASELINES)
    try:
        baseline = load_baseline(args.against, bdir)
        if args.agent:
            summary, run_dir = load_agent_summary(Path(args.summary) if args.summary else None, Path(args.results))
            if summary.get("tasks") is None:
                summary = {**summary, "tasks": agent_summary_tasks(summary, run_dir)}
            d = decide_agent(baseline, summary)
            metrics = AGENT_METRICS
        else:
            summary = load_summary(Path(args.summary) if args.summary else None, Path(args.results))
            d = decide(baseline, summary)
            metrics = DETECTOR_METRICS
    except GateError as e:
        print(f"gate: could not evaluate: {e}", file=sys.stderr)
        return 2
    text = render_decision(d, baseline, metrics)
    if args.quiet:
        print(text.rstrip("\n").splitlines()[-1])
    else:
        print(text, end="")
    return d.exit_code


def baseline_main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m evals baseline", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    pub = sub.add_parser("publish", help="commit the last run's summary as a baseline")
    pub.add_argument("--label", default=None, help="e.g. v0.1.1+evals (default: the run's git sha)")
    pub.add_argument("--summary", default=None, metavar="PATH",
                     help="summary.json to publish (default: the run evals/results/latest.json names)")
    pub.add_argument("--results", default=str(RESULTS), metavar="DIR")
    pub.add_argument("--baselines", default=None, metavar="DIR")
    pub.add_argument("--agent", action="store_true", help="publish an agent-run / calib-run summary as an agent baseline")
    ls = sub.add_parser("list", help="every published baseline")
    ls.add_argument("--baselines", default=None, metavar="DIR")
    ls.add_argument("--agent", action="store_true")
    tr = sub.add_parser("trends", help="regenerate evals/TRENDS.md")
    tr.add_argument("--baselines", default=str(BASELINES), metavar="DIR")
    args = ap.parse_args(argv)
    agent = bool(getattr(args, "agent", False))
    baselines_dir = Path(args.baselines) if args.baselines else (AGENT_BASELINES if agent else BASELINES)
    try:
        if args.cmd == "publish" and agent:
            summary, run_dir = load_agent_summary(Path(args.summary) if args.summary else None, Path(args.results))
            o = summary.get("overall") or {}
            if o.get("errors") or (o.get("passed") is not None and o.get("passed") != o.get("n")):
                print(f"warning: publishing a run with {o.get('errors', 0)} error(s) and "
                      f"{(o.get('n') or 0) - (o.get('passed') or 0)} failed trial(s)", file=sys.stderr)
            path = publish_agent(summary, args.label, baselines_dir, run_dir=run_dir)
            shown = path.relative_to(REPO) if path.is_relative_to(REPO) else path
            print(f"published agent baseline {json.loads(path.read_text())['label']} -> {shown}; latest.json updated")
            return 0
        if args.cmd == "publish":
            summary = load_summary(Path(args.summary) if args.summary else None, Path(args.results))
            head = git_sha()
            if summary.get("git_sha") not in (head, "nogit") and head != "nogit":
                print(f"warning: the run was graded at {summary.get('git_sha')}, HEAD is {head}",
                      file=sys.stderr)
            o = summary.get("overall") or {}
            if o.get("errors") or o.get("passed") != o.get("n"):
                print(f"warning: publishing a run with {o.get('errors', 0)} error(s) and "
                      f"{o.get('n', 0) - (o.get('passed') or 0)} failed task(s)", file=sys.stderr)
            path = publish(summary, args.label, baselines_dir)
            shown = path.relative_to(REPO) if path.is_relative_to(REPO) else path
            print(f"published {json.loads(path.read_text())['label']} -> {shown}; "
                  f"latest.json and TRENDS.md updated")
            return 0
        if args.cmd == "list":
            rows = list_baselines(baselines_dir)
            latest = None
            if (baselines_dir / "latest.json").is_file():
                latest = json.loads((baselines_dir / "latest.json").read_text()).get("label")
            for b in rows:
                o = b.get("overall") or {}
                mark = " (latest)" if b.get("label") == latest else ""
                print(f"{b.get('label')}{mark}  {b.get('published')}  run {b.get('run_id')}  "
                      f"tasks {o.get('tasks')}  recall {o.get('recall')}  precision {o.get('precision')}  "
                      f"errors {o.get('errors')}")
            if not rows:
                print("no baselines published")
            return 0
        if args.cmd == "trends":
            path = write_trends(baselines_dir)
            print(f"wrote {path}")
            return 0
    except GateError as e:
        print(f"baseline: {e}", file=sys.stderr)
        return 2
    return 2


if __name__ == "__main__":
    sys.exit(gate_main())
