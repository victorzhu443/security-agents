"""Eval cards (Layer 6): one Markdown card per registry entry, generated from the
registry, the case corpus, the grader docstrings and the last run.

    python -m evals card egress            # print
    python -m evals card egress --write    # write evals/cards/egress.md
    python -m evals card --all --write     # every card

Sections, in the order the labs' cards use them: task statement (the Layer 0 row of
EVALS-PLAN.md), construction, provenance of the historical-miss cases, metrics and
current numbers, known limitations, contamination policy. Everything here is derived
from files in the repo, so a card is regenerated, never edited.
"""
from __future__ import annotations

import argparse
import inspect
import json
import re
import sys
from pathlib import Path
from typing import Dict, List, Optional

from .graders import Case, default_graders
from .metrics import fmt_ci
from .registry import load_registry, select
from .run import RESULTS, discover

REPO = Path(__file__).resolve().parents[1]
CARDS_DIR = REPO / "evals" / "cards"
PLAN = REPO / "EVALS-PLAN.md"

# repos this program hardened; a historical-miss description names the one it came from
REPOS = ["research-replication-agent", "smart-dispatch", "firstplay", "study-hub",
         "security-agents", "toolkit"]


def layer0_row(prop: str, plan: Path = PLAN) -> Dict[str, str]:
    """The `| P<n> Name | invariant | oracle | violations |` row of Layer 0."""
    for line in plan.read_text().splitlines():
        if line.startswith(f"| {prop} "):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) >= 4:
                return {"name": cells[0], "invariant": cells[1], "oracle": cells[2],
                        "violations": cells[3]}
    return {"name": prop, "invariant": "(not found in EVALS-PLAN.md Layer 0)", "oracle": "", "violations": ""}


def repo_of(description: str) -> str:
    text = description.lower()
    for r in REPOS:
        if r in text:
            return "security-agents (toolkit)" if r == "toolkit" else r
    if "every project" in text or "every repo" in text:
        return "every project repo"
    return "—"


_VARIANT_SENTENCE = re.compile(r"^(vuln|clean|Clean|Fixed|The eval|Note)\b")


def flat(description: str) -> str:
    return " ".join(description.split()).replace("|", "\\|")


def what_was_missed(description: str) -> str:
    """The part of a description that states the miss: by convention the sentences
    before the first one describing the variants (`vuln ...`, `clean ...`, `Fixed ...`)."""
    sentences = re.split(r"(?<=[.!?])\s+", flat(description))
    keep = []
    for s in sentences:
        if keep and _VARIANT_SENTENCE.match(s):
            break
        keep.append(s)
    return " ".join(keep)


def gap_notes(cases: List[Case]) -> List[str]:
    """Sentences in case descriptions that pin a grader gap (closed or open)."""
    out = []
    for c in cases:
        flat = " ".join(c.description.split())
        for sent in re.split(r"(?<=[.!?])\s+", flat):
            if re.search(r"\bgap\b", sent, re.I):
                safe = sent.strip().replace("|", "\\|")
                out.append(f"`{c.id}`: {safe}")
    return out


def grader_docs(names: List[str]) -> Dict[str, str]:
    """Class docstring of each grader, else the docstring of the module defining it."""
    graders = default_graders(REPO)
    docs = {}
    for n in names:
        g = graders.get(n)
        if g is None:
            docs[n] = "(grader not registered)"
            continue
        doc = inspect.getdoc(type(g)) or inspect.getdoc(sys.modules.get(type(g).__module__)) or ""
        docs[n] = doc.strip()
    return docs


def last_run(results: Path = RESULTS) -> Optional[Dict]:
    latest = results / "latest.json"
    if not latest.exists():
        return None
    try:
        run_id = json.loads(latest.read_text())["run_id"]
        return json.loads((results / run_id / "summary.json").read_text())
    except (OSError, KeyError, ValueError):
        return None


def _quote(text: str, indent: str = "> ") -> str:
    return "\n".join(indent + line if line else indent.rstrip() for line in text.splitlines())


def render_card(entry: Dict, cases: List[Case], summary: Optional[Dict]) -> str:
    prop = entry["property"]
    row = layer0_row(prop)
    hist = [c for c in cases if c.origin == "historical-miss"]
    derived = [c for c in cases if c.origin != "historical-miss"]
    graders_used = sorted({c.grader for c in cases})
    L: List[str] = []
    L += [f"# Eval card — `{entry['id']}` ({row['name']})", "",
          f"*Generated by `python -m evals card {entry['name']} --write`; regenerate, do not edit.*", "",
          "| field | value |", "|---|---|",
          f"| id | `{entry['id']}` |", f"| version | {entry['version']} |",
          f"| property | {prop} — {entry.get('title', row['name'])} |",
          f"| task dir | `evals/{entry['task_dir']}` |",
          f"| graders | {', '.join(f'`{g}`' for g in entry['graders'])} |",
          f"| metrics | {', '.join(entry['metrics'])} |",
          f"| split | {entry['split']} |",
          f"| owner agent | [`{entry['owner_agent']}`](../../{entry['owner_agent']}) |",
          f"| tasks | {len(cases)} ({len(hist)} historical misses, {len(derived)} derived) |", ""]

    L += ["## Task statement", "",
          f"**Invariant.** {row['invariant']}", "",
          f"**Oracle.** {row['oracle']}", "",
          f"**Violation cases seeded.** {row['violations']}", "",
          "Source: `EVALS-PLAN.md` Layer 0.", ""]

    L += ["## Construction", "",
          f"Every task is a directory `evals/{entry['task_dir']}/<case>/` holding a `case.yaml` "
          "(the task record: `id`, `property`, `origin`, `grader`, `expect`, `description`, "
          "`canary`), a `vuln/` tree with exactly one planted violation, and a `clean/` twin — "
          "the same code with the violation fixed through the toolkit primitive. The grader "
          "scores both: the violation must be detected in `vuln/` (recall) and not in `clean/` "
          "(precision), so the clean twin is the baseline scored alongside every task.", "",
          "Origins, in the priority order of EVALS-PLAN.md Layer 2:", "",
          f"- **historical-miss** ({len(hist)}): a real miss from this program, encoded permanently.",
          f"- **derived** ({len(derived)}): a violation case from the Layer 0 row, in a code shape "
          "the historical cases do not already cover.", "",
          "| task | origin | grader | description |", "|---|---|---|---|"]
    for c in cases:
        L.append(f"| `{c.id}` | {c.origin} | `{c.grader}` | {flat(c.description)} |")
    L.append("")

    L += ["## Provenance of the historical misses", ""]
    if hist:
        L += ["| task | repo | what was missed |", "|---|---|---|"]
        for c in hist:
            L.append(f"| `{c.id}` | {repo_of(c.description)} | {what_was_missed(c.description)} |")
    else:
        L.append("No historical-miss case in this eval: every task is derived from the Layer 0 row.")
    L.append("")

    L += ["## Metrics and current numbers", "",
          "- **recall** = tasks whose `vuln/` the grader detected ÷ tasks, Wilson 95% CI.",
          "- **precision** = tasks whose `clean/` the grader did not flag ÷ tasks, Wilson 95% CI.",
          "- with `--trials K > 1`: **pass@k** (any of k) and **pass^k** (all of k) over tasks.", ""]
    block = (summary or {}).get("evals", {}).get(entry["id"])
    if summary and block and block.get("n"):
        L += [f"Last run `{summary['run_id']}` (toolkit {summary['toolkit_version']}, "
              f"{summary['generated'][:10]}, python {summary['python']}):", "",
              "| n | recall | precision | passed | errors |", "|---|---|---|---|---|",
              f"| {block['n']} | {fmt_ci(block['recall'], block['recall_ci95'])} | "
              f"{fmt_ci(block['precision'], block['precision_ci95'])} | {block['passed']} | {block['errors']} |", ""]
    else:
        L += ["No recorded run covers this eval yet: run `python -m evals run` and regenerate.", ""]

    L += ["## Known limitations", "",
          "From the grader docstrings (what each oracle can and cannot decide):", ""]
    for name, doc in grader_docs(graders_used).items():
        L += [f"### `{name}`", "", _quote(doc), ""]
    gaps = gap_notes(cases)
    if gaps:
        L += ["Grader gaps pinned in case descriptions:", ""] + [f"- {g}" for g in gaps] + [""]

    L += ["## Contamination policy", "",
          f"- **Canary.** Every `case.yaml`, every registry entry and `tasks.jsonl` carry the "
          f"string in `evals/registry/CANARY.txt` (BIG-bench convention): a model that can "
          f"reproduce it has seen this corpus in training, and its scores on it do not measure "
          f"the property.",
          f"- **Split.** This eval is `split: {entry['split']}`. Build-split cases are used to "
          "tune rules and defenses. The held-out split (`evals/heldout/`, EVALS-PLAN.md "
          "Phase 4) is sealed: written after the defenses, never used for tuning, and scored "
          "only in reports.",
          "- **No model in the loop.** Every grader is deterministic code; no LLM judges a "
          "result, so there is nothing to contaminate on the grading side.", ""]
    return "\n".join(L)


def card(name: str, *, results: Path = RESULTS) -> str:
    registry = load_registry()
    entry = registry[select(registry, [name])[0]]
    cases = [c for c in discover(REPO / "evals" / "cases") if c.property == entry["property"]]
    return render_card(entry, cases, last_run(results))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m evals card", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("name", nargs="?", help="eval name, id or property (e.g. egress, P4)")
    ap.add_argument("--all", action="store_true", help="every registry entry")
    ap.add_argument("--write", action="store_true", help="write evals/cards/<name>.md instead of printing")
    args = ap.parse_args(argv)
    if not args.name and not args.all:
        ap.error("give an eval name or --all")
    registry = load_registry()
    names = [e["name"] for e in registry.values()] if args.all else [registry[select(registry, [args.name])[0]]["name"]]
    for n in names:
        text = card(n)
        if args.write:
            CARDS_DIR.mkdir(parents=True, exist_ok=True)
            (CARDS_DIR / f"{n}.md").write_text(text)
            print(f"wrote evals/cards/{n}.md")
        else:
            print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
