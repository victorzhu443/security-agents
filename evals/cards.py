"""Eval cards (Layer 6): one Markdown card per registry entry, generated from the
registry, the case corpus, the grader docstrings and the last run.

    python -m evals card egress            # print
    python -m evals card egress --write    # write evals/cards/egress.md
    python -m evals card --all --write     # every card

Sections, in the order the labs' cards use them: task statement (the Layer 0 row of
EVALS-PLAN.md), construction, provenance of the historical-miss cases, metrics and
current numbers, known limitations, contamination policy. Everything here is derived
from files in the repo, so a card is regenerated, never edited.
"""
