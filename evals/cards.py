def calib_card(name: str = "calib-egress", *, results: Path = RESULTS) -> str:
    from .calib.runner import load_calib_registry
    entry = load_calib_registry()
    if name not in CALIB_CARD_NAMES + (entry["name"], entry["id"]):
        raise ValueError(f"no calibration card named {name!r}")
    return render_calib_card(entry, _calib_tasks(entry), _calib_last_run(results))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m evals card", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("name", nargs="?", help="eval name, id or property (e.g. egress, P4), or calib-egress")
    ap.add_argument("--all", action="store_true", help="every registry entry")
    ap.add_argument("--write", action="store_true", help="write evals/cards/<name>.md instead of printing")
    args = ap.parse_args(argv)
    if not args.name and not args.all:
        ap.error("give an eval name or --all")
    if args.name and (args.name in CALIB_CARD_NAMES or args.name.startswith("calib")):
        text = calib_card(args.name)
        if args.write:
            CARDS_DIR.mkdir(parents=True, exist_ok=True)
            (CARDS_DIR / "calib-egress.md").write_text(text)
            print("wrote evals/cards/calib-egress.md")
        else:
            print(text)
        return 0
    registry = load_registry()
    names = [e["name"] for e in registry.values()] if args.all else [registry[select(registry, [args.name])[0]]["name"]]
    for n in names:
        text = card(n)
        if args.write:
            CARDS_DIR.mkdir(parents=True, exist_ok=True)
            (CARDS_DIR / f"{n}.md").write_text(text)
            print(f"wrote evals/cards/{n}.md")
        else:
            print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
